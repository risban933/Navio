import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const domainsPath = path.join(repoRoot, "config", "google_domains.json");
const manifestPath = path.join(repoRoot, "Navio Extension", "Resources", "manifest.json");
const allowedHostsPath = path.join(repoRoot, "Navio Extension", "Resources", "lib", "allowedHosts.js");

function buildMatchPatterns(domain) {
  return [`*://${domain}/*`, `*://*.${domain}/*`];
}

function buildAllowedHostsModule(domains) {
  const serializedDomains = JSON.stringify(domains, null, 4);
  return `/**
 * This file is generated by scripts/generate-extension-config.mjs.
 * Do not edit it by hand.
 */

(function(root, factory) {
    const api = factory();

    if (typeof module !== "undefined" && module.exports) {
        module.exports = api;
    }

    root.NavioAllowedHosts = api;
})(typeof globalThis !== "undefined" ? globalThis : this, function() {
    "use strict";

    const DOMAIN_SUFFIXES = ${serializedDomains};

    function normalizeHost(host) {
        return typeof host === "string" ? host.trim().toLowerCase() : "";
    }

    function isAllowedGoogleHost(host) {
        const normalizedHost = normalizeHost(host);
        if (!normalizedHost) {
            return false;
        }

        return DOMAIN_SUFFIXES.some(function(domain) {
            return normalizedHost === domain || normalizedHost.endsWith("." + domain);
        });
    }

    return {
        DOMAIN_SUFFIXES: DOMAIN_SUFFIXES,
        isAllowedGoogleHost: isAllowedGoogleHost
    };
});
`;
}

function buildManifest(domains) {
  const matchPatterns = domains.flatMap(buildMatchPatterns);
  return {
    manifest_version: 3,
    default_locale: "en",
    name: "__MSG_extension_name__",
    description: "__MSG_extension_description__",
    version: "1.0.0",
    icons: {
      "16": "images/icon-16.png",
      "19": "images/icon-19.png",
      "32": "images/icon-32.png",
      "38": "images/icon-38.png",
      "48": "images/icon-48.png",
      "64": "images/icon-64.png",
      "96": "images/icon-96.png",
      "128": "images/icon-128.png",
      "256": "images/icon-256.png",
      "512": "images/icon-512.png"
    },
    background: {
      service_worker: "background.js"
    },
    content_scripts: [
      {
        js: [
          "lib/urlConversion.js",
          "lib/settings.js",
          "lib/stats.js",
          "content.js"
        ],
        matches: matchPatterns,
        run_at: "document_end"
      }
    ],
    action: {
      default_popup: "popup.html",
      default_icon: {
        "16": "images/icon-16.png",
        "19": "images/icon-19.png",
        "32": "images/icon-32.png",
        "38": "images/icon-38.png"
      },
      default_title: "Navio"
    },
    permissions: [
      "nativeMessaging",
      "storage"
    ],
    host_permissions: matchPatterns
  };
}

async function main() {
  const domainsFile = await readFile(domainsPath, "utf8");
  const parsed = JSON.parse(domainsFile);
  const domains = [...new Set((parsed.domains || []).filter(Boolean))];

  if (domains.length === 0) {
    throw new Error("config/google_domains.json must contain at least one domain");
  }

  await mkdir(path.dirname(allowedHostsPath), { recursive: true });

  await writeFile(
    allowedHostsPath,
    buildAllowedHostsModule(domains),
    "utf8"
  );

  await writeFile(
    manifestPath,
    JSON.stringify(buildManifest(domains), null, 4) + "\n",
    "utf8"
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
